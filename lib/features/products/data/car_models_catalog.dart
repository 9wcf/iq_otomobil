/// خيار يدوي عند عدم وجود الموديل في القائمة.
const kCarModelOtherOption = 'أخرى';

List<String> carModelsForBrandId(String? brandId) {
  if (brandId == null || brandId.isEmpty) return const [];
  return kCarModelsByBrandId[brandId] ?? const [];
}

List<String> carModelsForStorageLabel(String? storageLabel) {
  final brand = brandByStorageLabel(storageLabel);
  if (brand == null) return const [];
  return carModelsForBrandId(brand.id);
}

/// يطابق نص الموديل المخزّن مع قائمة الماركة.
String? matchCatalogModel(String? brandId, String? modelText) {
  final raw = modelText?.trim() ?? '';
  if (raw.isEmpty || brandId == null) return null;
  for (final m in carModelsForBrandId(brandId)) {
    if (m == raw || raw.contains(m) || m.contains(raw)) return m;
  }
  return null;
}
